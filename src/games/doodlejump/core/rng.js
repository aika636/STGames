// mulberry32 скопирован из соседних игр (судоку, змейка), а не импортирован: игры друг у
// друга ничего не берут — иначе удаление одной игры ломало бы другую, и папку нельзя было
// бы выкинуть целиком. Пятнадцать строк дешевле кросс-игровой зависимости.

export function mulberry32(seed) {
    let a = seed >>> 0;
    return function rng() {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}
