// Картинки нужного размера. Размер поля и есть уровень: у 5×5 свой набор, у 10×10 свой.
export function picturesFor(cols, rows) {
    return PICTURES.filter((pic) => pic.cols === cols && pic.rows === rows);
}

// Плоский массив 0/1 — тот же формат, в котором генератор отдаёт картинку дальше.
export function gridOf(pic) {
    const grid = new Uint8Array(pic.cols * pic.rows);
    for (let y = 0; y < pic.rows; y++) {
        const row = pic.cells[y];
        for (let x = 0; x < pic.cols; x++) {
            grid[y * pic.cols + x] = row[x] === '#' ? 1 : 0;
        }
    }
    return grid;
}
