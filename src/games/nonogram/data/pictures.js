// Банк картинок нонограммы. Настоящая нонограмма — не шум, который случайно оказался
// однозначным, а рисунок: собрав его, игрок видит кота, кораблик или гриб. Поэтому
// картинки нарисованы руками, по одному набору на каждый размер поля (5×5 — 30 штук,
// 10×10 — 34, 15×15 — 36, всего 100), а генератор (core/generator.js) берёт их отсюда
// и лишь в крайнем случае откатывается на случайную заливку.
//
// Клетки — строки из '#' (закрашено) и '.' (пусто), по строке на ряд картинки. Такой
// формат читается и правится глазами: рисунок в исходнике виден как рисунок.
//
// Требование к каждой картинке — та же честность, что и у случайной: подсказки должны
// решаться линейными выводами, без перебора с возвратом. Это проверяет тест
// tests/nonogram/pictures.test.mjs, он же ловит опечатки в ширине строк. Новую картинку
// добавлять только после того, как тест на ней прошёл: неоднозначный рисунок игрок
// не соберёт — он вынужден будет угадывать, а победа сверяется с одним конкретным
// вариантом.
//
// Что чаще всего не проходит проверку (проверено на этом банке): кольца и бублики
// с дыркой посередине, диагонали в одну клетку и мелкие детали, висящие в воздухе
// отдельно от тела рисунка, — у них по нескольку решений. Лечится утолщением стенок
// и «пришиванием» детали к основной фигуре.
//
// Модуль грузится статическим import, в отличие от словарей «Слов» и кроссворда: банк
// весит единицы килобайт, а картинка нужна синхронно, в момент открытия экрана.

// Название показывается только после победы: до неё это спойлер.
function picture(id, title, cells) {
    return Object.freeze({
        id,
        title,
        cols: cells[0].length,
        rows: cells.length,
        cells: Object.freeze(cells),
    });
}

